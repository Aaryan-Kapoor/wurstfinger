import Foundation
@testable import WurstfingerKit

/// How gentle "gentle" is: letters that may leave their shipped slot.
enum LabBudget {
    static let gentle = 4
    static let frontier = [2, 4, 6, 8]
}

/// Variants that are hand-written and shipped already; the pipeline reports
/// them but never regenerates them, so nobody's layout changes under them.
enum LabFrozen {
    static let variantIds: Set<String> = ["en_US_optimized"]
}

/// Everything the pipeline found out about one language.
struct LanguageResult {
    var languageId: String
    var title: String
    var corpus: [String: String]
    var coverage: Double
    var untypable: [(character: String, count: Int)]
    var shipped: ScoredLayout
    var gentle: ScoredLayout
    var full: ScoredLayout
    /// Best cost at each frontier budget.
    var frontier: [(budget: Int, layout: ScoredLayout)]
    /// Hand-shipped variants of this language, scored under the same corpus.
    var frozen: [(id: String, layout: ScoredLayout)]
}

enum LabPipeline {
    /// Corpus table → typable characters for `problem`.
    static func isTypable(problem: LayoutProblem) -> (String) -> Bool {
        var letterIndex: [String: Int] = [:]
        for (index, letter) in problem.letters.enumerated() { letterIndex[letter] = index }
        return { TextModel.expand($0, problem: problem, letterIndex: letterIndex) != nil }
    }

    /// Reads a `word count` list into a table for `languageId`'s layout.
    static func derive(
        languageId: String, wordList: String, limit: Int = .max
    ) throws -> (table: CorpusTable, kept: Int, seen: Int) {
        let problem = try LayoutProblem(languageId: languageId)
        return CorpusTable.fromWordList(
            wordList, locale: problem.locale, isTypable: isTypable(problem: problem), limit: limit
        )
    }

    static func optimize(
        languageId: String, table: CorpusTable, settings: AnnealingSettings,
        budget: Int = LabBudget.gentle, frontier budgets: [Int] = LabBudget.frontier
    ) throws -> LanguageResult {
        let problem = try LayoutProblem(languageId: languageId)
        let text = TextModel(table: table, problem: problem)
        let optimizer = LayoutOptimizer(problem: problem, text: text)
        let shipped = optimizer.score(problem.base)
        let full = optimizer.optimize(maxMoved: nil, settings: settings)
        let gentle = optimizer.optimize(maxMoved: budget, settings: settings)
        var frontier: [(Int, ScoredLayout)] = []
        for k in budgets {
            frontier.append((k, k == budget ? gentle : optimizer.optimize(maxMoved: k, settings: settings)))
        }
        var frozen: [(String, ScoredLayout)] = []
        for id in LabFrozen.variantIds.sorted() where id.hasPrefix(languageId + "_") {
            if let variant = try? LayoutProblem(languageId: id), variant.isPermutation(variant.base),
               Set(variant.movableSlots) == Set(problem.movableSlots), Set(variant.letters) == Set(problem.letters) {
                frozen.append((id, optimizer.score(variant.base)))
            }
        }
        let title = KeyboardRegistry.load(id: languageId)?.title ?? languageId
        return LanguageResult(
            languageId: languageId, title: title, corpus: table.meta, coverage: text.coverage,
            untypable: text.untypable.sorted { ($1.value, $0.key) < ($0.value, $1.key) }
                .prefix(8).map { ($0.key, $0.value) },
            shipped: shipped, gentle: gentle, full: full, frontier: frontier, frozen: frozen
        )
    }

    // MARK: Generated Swift

    private static let slotNames = GridSlot.allSlots.joined().map { $0 }

    /// The data file the keyboard ships: variant id → key slot → gesture → letter.
    static func generatedSwift(_ results: [LanguageResult], settings: AnnealingSettings, budget: Int) -> String {
        var lines = [
            "//",
            "//  OptimizedArrangements+Data.generated.swift",
            "//  Wurstfinger",
            "//",
            "//  GENERATED by `layoutlab optimize` (see docs/layout-science.md). Do not edit: change the",
            "//  corpus tables under tools/layout-lab/corpora or the pipeline and regenerate.",
            "//  seed \(settings.seed), \(settings.restarts) restarts x \(settings.steps) steps, gentle = at most \(budget) letters moved.",
            "//",
            "",
            "import Foundation",
            "",
            "extension OptimizedArrangements {",
            "    /// Variant id → key slot → gesture → letter. `_optimized` is the gentle",
            "    /// variant, `_full` the unconstrained optimum, both under the language's corpus.",
            "    static let table: [String: [String: [GestureType: String]]] = [",
        ]
        for result in results.sorted(by: { $0.languageId < $1.languageId }) {
            for (suffix, layout) in [("optimized", result.gentle), ("full", result.full)] {
                let id = "\(result.languageId)_\(suffix)"
                if LabFrozen.variantIds.contains(id) { continue }
                lines.append("        // \(result.title): cost \(format(layout.cost)) vs shipped \(format(result.shipped.cost)) bits per character; moved \(layout.moved.joined(separator: " "))")
                lines.append("        \"\(id)\": [")
                var byKey: [Int: [LabSlot: String]] = [:]
                for (slot, letter) in layout.assignment { byKey[slot.key, default: [:]][slot] = letter }
                for key in byKey.keys.sorted() {
                    let entries = byKey[key]!.keys.sorted().map { slot in
                        ".\(slot.gesture.rawValue): \(literal(byKey[key]![slot]!))"
                    }
                    let joined = entries.joined(separator: ", ")
                    if joined.count <= 90 {
                        lines.append("            GridSlot.\(slotNames[key]): [\(joined)],")
                    } else {
                        // Long keys (the centre) wrap four to a line.
                        lines.append("            GridSlot.\(slotNames[key]): [")
                        for start in stride(from: 0, to: entries.count, by: 4) {
                            lines.append("                " + entries[start ..< min(start + 4, entries.count)].joined(separator: ", ") + ",")
                        }
                        lines.append("            ],")
                    }
                }
                lines.append("        ],")
            }
        }
        lines.append("    ]")
        lines.append("}")
        return lines.joined(separator: "\n") + "\n"
    }

    private static func literal(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    static func format(_ value: Double) -> String { String(format: "%.4f", value) }

    private static func percent(_ value: Double, versus baseline: Double) -> String {
        String(format: "%+.2f %%", 100 * (value - baseline) / baseline)
    }

    // MARK: Report

    /// The per-language results as Markdown tables.
    static func report(_ results: [LanguageResult], settings: AnnealingSettings, budget: Int) -> String {
        var out = "| language | corpus coverage | shipped | gentle (≤\(budget) moved) | Δ | full | Δ | gentle moves |\n"
        out += "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |\n"
        for r in results.sorted(by: { $0.languageId < $1.languageId }) {
            out += "| \(r.title) `\(r.languageId)` | \(String(format: "%.1f %%", 100 * r.coverage)) | \(format(r.shipped.cost)) "
            out += "| \(format(r.gentle.cost)) | \(percent(r.gentle.cost, versus: r.shipped.cost)) "
            out += "| \(format(r.full.cost)) | \(percent(r.full.cost, versus: r.shipped.cost)) "
            out += "| \(r.gentle.moved.joined(separator: " ")) |\n"
        }
        out += "\nFrontier (best cost with at most K letters moved, change against the shipped layout):\n\n"
        out += "| language | " + LabBudget.frontier.map { "K=\($0)" }.joined(separator: " | ") + " | full (letters moved) |\n"
        out += "| --- | " + LabBudget.frontier.map { _ in "---:" }.joined(separator: " | ") + " | ---: |\n"
        for r in results.sorted(by: { $0.languageId < $1.languageId }) {
            let cells = r.frontier.map { percent($0.layout.cost, versus: r.shipped.cost) }
            out += "| `\(r.languageId)` | \(cells.joined(separator: " | ")) | \(percent(r.full.cost, versus: r.shipped.cost)) (\(r.full.moved.count)) |\n"
        }
        let frozen = results.flatMap { r in r.frozen.map { (r, $0) } }
        if !frozen.isEmpty {
            out += "\nHand-shipped variants, scored under the same corpus (never regenerated):\n\n"
            for (r, variant) in frozen {
                out += "* `\(variant.id)`: \(format(variant.layout.cost)) bits (\(percent(variant.layout.cost, versus: r.shipped.cost)) against `\(r.languageId)`), moved \(variant.layout.moved.joined(separator: " "))\n"
            }
        }
        return out
    }
}

extension LabPipeline {
    /// Whether the model applies to the layout `id`: a shipped base layout of a
    /// cased script (variants are outputs, not inputs).
    static func isOptimizable(_ id: String) -> Bool {
        guard let metadata = KeyboardRegistry.available.first(where: { $0.id == id }),
              metadata.family == .messagEase, metadata.variantOf == nil
        else { return false }
        return (try? LayoutProblem(languageId: id)) != nil
    }
}
