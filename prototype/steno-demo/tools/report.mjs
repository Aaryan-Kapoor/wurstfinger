// Collects the evaluation and robustness results into one module the demo can show.
//
//   node tools/report.mjs
//
// Runs tools/evaluate.mjs and tools/robustness.mjs and writes src/eval.generated.js.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const run = script => JSON.parse(execFileSync(process.execPath, [path.join(here, script), '--json'], { maxBuffer: 1 << 26 }).toString());
const evaluation = run('evaluate.mjs');
const robustness = run('robustness.mjs');

const slim = {};
for (const [corpus, r] of Object.entries(evaluation)) {
  slim[corpus] = {
    messages: r.messages, chars: r.chars, letterWpm: +r.detail.wpm.toFixed(1),
    stages: [...new Set(r.rows.map(x => x.stage))].map(stage => {
      const [base, slow, recall] = r.rows.filter(x => x.stage === stage);
      return {
        stage, gesturesPerWord: +base.gesturesPerWord.toFixed(2), saving: +(base.gestureSaving * 100).toFixed(1),
        wpm: +base.wpm.toFixed(1), wpmSlow: +slow.wpm.toFixed(1), wpmRecall: +recall.wpm.toFixed(1),
        share: Object.fromEntries(['flick', 'hook', 'ending', 'brief', 'spell'].map(k => [k, +(base.tally[k] / base.tally.words * 100).toFixed(1)])),
      };
    }),
  };
}
const robust = Object.fromEntries(Object.entries(robustness).map(([level, r]) => [level, {
  accuracy: +(r.accuracy * 100).toFixed(2),
  shapes: Object.fromEntries(Object.entries(r.confusion).map(([name, c]) => [name, +(c.right / c.n * 100).toFixed(1)])),
}]));

fs.writeFileSync(path.join(here, '..', 'src', 'eval.generated.js'),
  `// Generated by tools/report.mjs. Do not edit.\nexport default ${JSON.stringify({ evaluation: slim, robustness: robust }, null, 1)};\n`);
console.log('wrote src/eval.generated.js');
