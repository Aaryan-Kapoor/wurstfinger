#!/usr/bin/env python3
"""Generates Sources/.../ComposeRuleSet+Marks.swift from Unicode canonical composition.

Flickboard (the keyboard Wurstfinger is measured against, see
docs/layout-parity.md) composes a dead key with the previous letter by asking
Unicode whether `base + combining mark` has a precomposed form. The global
rule table is a hand-curated subset of that, so this script emits the rest: for
every trigger Wurstfinger binds (or now binds) to a key, every Latin, Greek
and Cyrillic base letter whose composition with that trigger's combining mark is
a single code point and is not already in `ComposeRuleSet.global`.

Usage (from the repository root):
    python3 -I scripts/gen_compose_marks.py \\
        > Sources/WurstfingerKit/Keyboard/Definition/Compose/ComposeRuleSet+Marks.swift
It reads the existing table straight from ComposeRuleSet+Global.swift, so the
output only ever adds to it. Stdlib only; needs Python 3.9+.
"""
import re
import sys
import unicodedata

GLOBAL_SOURCE = "Sources/WurstfingerKit/Keyboard/Definition/Compose/ComposeRuleSet+Global.swift"
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def unescape(literal):
    literal = re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), literal)
    return literal.replace('\\"', '"').replace("\\\\", "\\")


def read_global(path):
    """trigger -> {base: result}, parsed from the Swift literal."""
    table = {}
    current = None
    for line in open(path, encoding="utf8"):
        stripped = line.strip()
        if stripped.startswith("//") or stripped.startswith("///"):
            continue
        if stripped.startswith('"') and stripped.endswith(": ["):
            current = unescape(LITERAL.search(stripped).group(1))
            table[current] = {}
        elif current is not None and stripped.startswith('"'):
            literals = [unescape(m) for m in LITERAL.findall(stripped)]
            for base, result in zip(literals[0::2], literals[1::2]):
                table[current][base] = result
        elif stripped.startswith("]"):
            current = None
    return table

# trigger (as Wurstfinger spells it) -> combining mark it stands for
TRIGGERS = [
    ("ˋ", "̀"),  # grave
    ("´", "́"),  # acute
    ("^", "̂"),  # circumflex
    ("~", "̃"),  # tilde
    ("¯", "̄"),  # macron
    ("˘", "̆"),  # breve
    ("°", "̊"),  # ring above
    ("¨", "̈"),  # diaeresis
    ("˝", "̋"),  # double acute
    ("ˇ", "̌"),  # caron
    ("¸", "̧"),  # cedilla
    ("˛", "̨"),  # ogonek
]

BASE_RANGES = [
    (0x0041, 0x005A), (0x0061, 0x007A),  # Basic Latin letters
    (0x00C0, 0x024F),                    # Latin-1 Supplement .. Latin Extended-B
    (0x1E00, 0x1EFF),                    # Latin Extended Additional
    (0x0386, 0x03CE),                    # Greek
    (0x0400, 0x04FF),                    # Cyrillic
]


def swift_string(text):
    out = []
    for ch in text:
        cp = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif cp < 0x20 or cp in (0x300, 0x301) or 0x300 <= cp < 0x370:
            out.append("\\u{%X}" % cp)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    existing = read_global(sys.argv[1] if len(sys.argv) > 1 else GLOBAL_SOURCE)
    table = {}
    for trigger, mark in TRIGGERS:
        have = existing.get(trigger, {})
        for lo, hi in BASE_RANGES:
            for cp in range(lo, hi + 1):
                base = chr(cp)
                if not base.isalpha() or base in have:
                    continue
                composed = unicodedata.normalize("NFC", base + mark)
                if len(composed) == 1 and composed != base:
                    table.setdefault(trigger, {})[base] = composed
    print("//")
    print("//  ComposeRuleSet+Marks.swift")
    print("//  Wurstfinger")
    print("//")
    print("//  Dead-key compositions Unicode defines and the hand-written global table lacks.")
    print("//  Generated by scripts/gen_compose_marks.py: do not edit by hand, regenerate.")
    print("//")
    print()
    print("import Foundation")
    print()
    print("extension ComposeRuleSet {")
    print("    /// Compositions of a dead key with a base letter that Unicode defines (the")
    print("    /// base plus the key's combining mark has a precomposed form) and")
    print("    /// `ComposeRuleSet.global` does not list: ǎ ǐ ǒ ǔ with the caron, ā ē ī ō ū")
    print("    /// with the macron, ą ę į ų with the ogonek, ş ţ ģ ķ with the cedilla, ő ű")
    print("    /// with the double acute, and the long tail of Latin, Greek and Cyrillic")
    print("    /// letters behind them. This is what makes every dead key compose with every")
    print("    /// letter the way Flickboard's does (see docs/layout-parity.md).")
    print("    ///")
    print("    /// Kept apart from `global` on purpose: `ComposeEngine` builds the 🅒 accent")
    print("    /// cycles from `global` alone, because folding these in would change the")
    print("    /// order variants come up in, which is muscle memory. These rules compose")
    print("    /// only.")
    print("    static let unicodeMarks = ComposeRuleSet(rules: [")
    for trigger, _ in TRIGGERS:
        entries = table.get(trigger)
        if not entries:
            continue
        print("        %s: [" % swift_string(trigger))
        items = sorted(entries.items())
        line = "            "
        for base, composed in items:
            piece = "%s: %s, " % (swift_string(base), swift_string(composed))
            if len(line) + len(piece) > 110:
                print(line.rstrip())
                line = "            "
            line += piece
        if line.strip():
            print(line.rstrip())
        print("        ],")
    print("    ])")
    print("}")


main()
